/**
 * Interface translations (English + Arabic).
 *
 * To change wording, edit the strings below. The Arabic object is typed
 * against the English one, so a missing key is a type error (`npm run check`).
 * The brand name "MEZO TECH" is intentionally never translated.
 */

export type Lang = 'en' | 'ar';
export const defaultLang: Lang = 'en';
export const langs: Lang[] = ['en', 'ar'];

export const languages = {
  en: { label: 'EN', name: 'English', dir: 'ltr', locale: 'en-GB', ogLocale: 'en_US' },
  ar: { label: 'AR', name: 'العربية', dir: 'rtl', locale: 'ar', ogLocale: 'ar_AR' },
} as const satisfies Record<Lang, { label: string; name: string; dir: 'ltr' | 'rtl'; locale: string; ogLocale: string }>;

export function isLang(value: unknown): value is Lang {
  return value === 'en' || value === 'ar';
}

/** Arabic counting rules: 1 / 2 / 3–10 / 11+ use different noun forms. */
function arCount(n: number, one: string, two: string, few: string, many: string): string {
  if (n === 1) return one;
  if (n === 2) return two;
  if (n >= 3 && n <= 10) return `${n} ${few}`;
  return `${n} ${many}`;
}

